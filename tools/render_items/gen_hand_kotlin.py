"""Writes ui/character/weapon/FirstPersonSprites.kt from hand_sprites.json (run after render_hand.py)."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
meta = json.load(open(os.path.join(HERE, "hand_sprites.json")))
ppu = meta["ppu"]


def off(name):
    x, y = meta[name]
    return f"Offset({x}f, {y}f)"


rows = []
for kind, base in (("RUSTY_DAGGER", "fp_dagger_rusty"), ("DAGGER", "fp_dagger")):
    rows.append(f"        WeaponKind.{kind} -> Sprite(R.drawable.{base}, {off(base)})")
for kind, base in (("SHORT_SWORD", "fp_short_sword"), ("MACE", "fp_mace"), ("AXE", "fp_axe")):
    cases = "\n".join(f"            Rarity.{r.upper()} -> Sprite(R.drawable.{base}_{r}, {off(base + '_' + r)})"
                      for r in ("common", "uncommon", "rare", "epic", "legendary"))
    rows.append(f"        WeaponKind.{kind} -> when (look.rarity) {{\n{cases}\n        }}")
table = "\n".join(rows)

card_rows = []
for kind, base in (("RUSTY_DAGGER", "wc_dagger_rusty"), ("DAGGER", "wc_dagger")):
    card_rows.append(f"        WeaponKind.{kind} -> Sprite(R.drawable.{base}, {off(base)})")
for kind, base in (("SHORT_SWORD", "wc_short_sword"), ("MACE", "wc_mace"), ("AXE", "wc_axe")):
    cases = "\n".join(f"            Rarity.{r.upper()} -> Sprite(R.drawable.{base}_{r}, {off(base + '_' + r)})"
                      for r in ("common", "uncommon", "rare", "epic", "legendary"))
    card_rows.append(f"        WeaponKind.{kind} -> when (look.rarity) {{\n{cases}\n        }}")
card_table = "\n".join(card_rows)
card_ppu = meta["card_ppu"]

src = f'''package com.idlerpg.game.ui.character.weapon

import android.content.res.Resources
import android.graphics.BitmapFactory
import android.util.LruCache
import androidx.compose.ui.geometry.Offset
import androidx.compose.ui.graphics.FilterQuality
import androidx.compose.ui.graphics.ImageBitmap
import androidx.compose.ui.graphics.asImageBitmap
import androidx.compose.ui.graphics.drawscope.DrawScope
import androidx.compose.ui.graphics.drawscope.withTransform
import androidx.compose.ui.unit.IntOffset
import androidx.compose.ui.unit.IntSize
import com.idlerpg.game.R
import com.idlerpg.game.data.Rarity
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

/**
 * Raytraced first-person arm and held weapons (`tools/render_items/render_hand.py`, generated by
 * `gen_hand_kotlin.py` - do not edit by hand). All sprites share one scale ([PPU] pixels per hand-space unit)
 * and are placed by the pixel position of the grip centre, so they slot into the vector pose system of
 * [drawFirstPersonWeapon] unchanged. The vector painters stay as fallback until the bitmaps are decoded.
 */
internal object FirstPersonSprites {{

    const val PPU = {ppu}f

    class Sprite(val res: Int, val grip: Offset)

    /** Pixels per hand-space unit of the larger character-tab pictures ([cardOf]). */
    const val CARD_PPU = {card_ppu}f

    val handBack = Sprite(R.drawable.hand_back, {off("hand_back")})
    val handFront = Sprite(R.drawable.hand_front, {off("hand_front")})
    val fist = Sprite(R.drawable.hand_fist, {off("hand_fist")})

    fun weaponOf(look: WeaponLook): Sprite? = when (look.kind) {{
{table}
        WeaponKind.FIST -> null
    }}

    /** Large picture of the weapon for the character tab (same model and hand space, higher resolution). */
    fun cardOf(look: WeaponLook): Sprite? = when (look.kind) {{
{card_table}
        WeaponKind.FIST -> null
    }}

    private val cache = object : LruCache<Int, ImageBitmap>(24 * 1024 * 1024) {{
        override fun sizeOf(key: Int, value: ImageBitmap): Int = value.width * value.height * 4
    }}

    fun peek(sprite: Sprite): ImageBitmap? = cache.get(sprite.res)

    /** Decodes everything [look] needs (arm layers + weapon, or the fist) off the main thread. */
    suspend fun preload(resources: Resources, look: WeaponLook) {{
        val need = if (look.kind == WeaponKind.FIST) listOf(fist) else listOfNotNull(handBack, handFront, weaponOf(look))
        for (s in need) {{
            if (cache.get(s.res) != null) continue
            val bmp = withContext(Dispatchers.Default) {{
                runCatching {{ BitmapFactory.decodeResource(resources, s.res) }}.getOrNull()
            }} ?: continue
            cache.put(s.res, bmp.asImageBitmap())
        }}
    }}

    /** Decodes only the weapon of [look] (paper doll), or its large picture if [card]; true once cached. */
    suspend fun preloadWeapon(resources: Resources, look: WeaponLook, card: Boolean = false): Boolean {{
        val s = (if (card) cardOf(look) else weaponOf(look)) ?: return false
        if (cache.get(s.res) == null) {{
            val bmp = withContext(Dispatchers.Default) {{
                runCatching {{ BitmapFactory.decodeResource(resources, s.res) }}.getOrNull()
            }} ?: return false
            cache.put(s.res, bmp.asImageBitmap())
        }}
        return true
    }}

    /** Draws [img] in hand space (grip centre at the origin, 1 unit = 1 hand-space unit). */
    fun DrawScope.drawInHandSpace(img: ImageBitmap, sprite: Sprite, ppu: Float = PPU) {{
        withTransform({{
            scale(1f / ppu, 1f / ppu, Offset.Zero)
            translate(-sprite.grip.x, -sprite.grip.y)
        }}) {{
            val size = IntSize(img.width, img.height)
            drawImage(img, IntOffset.Zero, size, IntOffset.Zero, size, filterQuality = FilterQuality.High)
        }}
    }}
}}
'''
path = os.path.join(ROOT, "app", "src", "main", "java", "com", "idlerpg", "game", "ui", "character", "weapon", "FirstPersonSprites.kt")
open(path, "w", encoding="utf-8", newline="\n").write(src)
print("wrote", path)
