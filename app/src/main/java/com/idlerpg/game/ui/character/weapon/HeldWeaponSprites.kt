package com.idlerpg.game.ui.character.weapon

import android.content.res.Resources
import android.graphics.BitmapFactory
import android.util.LruCache
import androidx.compose.ui.geometry.Offset
import androidx.compose.ui.graphics.FilterQuality
import androidx.compose.ui.graphics.ImageBitmap
import androidx.compose.ui.graphics.asImageBitmap
import androidx.compose.ui.graphics.drawscope.DrawScope
import androidx.compose.ui.graphics.drawscope.withTransform
import androidx.compose.ui.unit.IntOffset
import androidx.compose.ui.unit.IntSize
import com.idlerpg.game.R
import com.idlerpg.game.data.Rarity
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

/**
 * Raytraced first-person sprites of the gloved hand with the weapon (`tools/render_items/weapons_hand.py`,
 * `weapon_held_*.webp`). The animation system poses a "hand space" (grip centre at the origin, weapon to -y,
 * forearm towards +y); a sprite is drawn into it via its grip anchor and the hand units per sprite pixel,
 * so all key frames, impact points and trails of [FirstPersonWeapon] stay valid. Falls back to the vector
 * painters while a sprite is not loaded.
 */
internal object HeldWeaponSprites {

    /** @property gripX/gripY grip centre in sprite pixels; @property unitsPerPx hand-space units per sprite pixel. */
    class Meta(val res: Int, val gripX: Float, val gripY: Float, val unitsPerPx: Float)

    private const val CACHE_BYTES = 40 * 1024 * 1024

    private val cache = object : LruCache<Int, ImageBitmap>(CACHE_BYTES) {
        override fun sizeOf(key: Int, value: ImageBitmap): Int = value.width * value.height * 4
    }

    // Generated by tools/render_items/weapons_hand.py (weapon_held_meta.json).
    private val DAGGER = Meta(R.drawable.weapon_held_dagger, 108.15f, 559.63f, 0.45051f)
    private val DAGGER_RUSTY = Meta(R.drawable.weapon_held_dagger_rusty, 108.15f, 559.63f, 0.45051f)
    private val FIST = Meta(R.drawable.weapon_held_fist, 127.94f, 229.40f, 0.31061f)
    private val SWORD = rarities(162.10f, 699.47f, 0.45803f,
        R.drawable.weapon_held_short_sword_common, R.drawable.weapon_held_short_sword_uncommon,
        R.drawable.weapon_held_short_sword_rare, R.drawable.weapon_held_short_sword_epic,
        R.drawable.weapon_held_short_sword_legendary)
    private val MACE = rarities(116.84f, 699.47f, 0.46532f,
        R.drawable.weapon_held_mace_common, R.drawable.weapon_held_mace_uncommon,
        R.drawable.weapon_held_mace_rare, R.drawable.weapon_held_mace_epic,
        R.drawable.weapon_held_mace_legendary)
    private val AXE = rarities(201.73f, 691.82f, 0.49210f,
        R.drawable.weapon_held_axe_common, R.drawable.weapon_held_axe_uncommon,
        R.drawable.weapon_held_axe_rare, R.drawable.weapon_held_axe_epic,
        R.drawable.weapon_held_axe_legendary)

    private fun rarities(gx: Float, gy: Float, k: Float, vararg res: Int): List<Meta> = res.map { Meta(it, gx, gy, k) }

    private fun metaOf(look: WeaponLook): Meta = when (look.kind) {
        WeaponKind.RUSTY_DAGGER -> DAGGER_RUSTY
        WeaponKind.DAGGER -> DAGGER
        WeaponKind.SHORT_SWORD -> SWORD[look.rarity.ordinal.coerceIn(0, Rarity.entries.size - 1)]
        WeaponKind.MACE -> MACE[look.rarity.ordinal.coerceIn(0, Rarity.entries.size - 1)]
        WeaponKind.AXE -> AXE[look.rarity.ordinal.coerceIn(0, Rarity.entries.size - 1)]
        WeaponKind.FIST -> FIST
    }

    /** The loaded sprite of [look] with its metadata, or null while it is not cached. */
    fun peek(look: WeaponLook): Pair<ImageBitmap, Meta>? {
        val meta = metaOf(look)
        return cache.get(meta.res)?.let { it to meta }
    }

    /** Decodes the sprite of [look] on a background thread (no-op if cached). */
    suspend fun preload(resources: Resources, look: WeaponLook) {
        val meta = metaOf(look)
        if (cache.get(meta.res) != null) return
        val bmp = withContext(Dispatchers.Default) {
            runCatching { BitmapFactory.decodeResource(resources, meta.res) }.getOrNull()
        } ?: return
        cache.put(meta.res, bmp.asImageBitmap())
    }

    /** Draws the sprite into the current hand space (grip centre at the origin). */
    fun draw(scope: DrawScope, held: Pair<ImageBitmap, Meta>) = with(scope) {
        val (img, meta) = held
        val k = meta.unitsPerPx
        withTransform({
            translate(-meta.gripX * k, -meta.gripY * k)
            scale(k, k, Offset.Zero)
        }) {
            val size = IntSize(img.width, img.height)
            drawImage(img, IntOffset.Zero, size, IntOffset.Zero, size, filterQuality = FilterQuality.High)
        }
    }
}
